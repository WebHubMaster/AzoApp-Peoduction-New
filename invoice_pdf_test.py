    log(f"\n{'='*80}", Colors.BOLD)
    log(f"FETCHING INVOICES", Colors.BOLD)
    log(f"{'='*80}", Colors.BOLD)
    
    invoice_types = ["booking", "cancellation", "refund", "withdrawal"]
    invoices_by_type = {}
    
    for inv_type in invoice_types:
        log(f"\n🔍 Fetching {inv_type} invoices...", Colors.BLUE)
        
        # Try admin first (can see all)
        invoices = get_invoices_by_type(admin_token, inv_type)
        
        if not invoices:
            # Try customer
            invoices = get_invoices_by_type(customer_token, inv_type)
        
        if not invoices:
            # Try partner
            invoices = get_invoices_by_type(partner_token, inv_type)
        
        if not invoices:
            # Try merchant
            invoices = get_invoices_by_type(merchant_token, inv_type)
        
        if invoices:
            invoices_by_type[inv_type] = invoices[0]  # Take first invoice
            log(f"  ✅ Found {inv_type} invoice: {invoices[0]['invoice_number']}", Colors.GREEN)
        else:
            log(f"  ⚠️  No {inv_type} invoices found", Colors.YELLOW)
    
    if not invoices_by_type:
        log(f"\n❌ No invoices found to test", Colors.RED)
        return 1
    
    # Run tests
    log(f"\n{'='*80}", Colors.BOLD)
    log(f"TEST 1 & 2: PDF ENGINE + HTML PREVIEW", Colors.BOLD)
    log(f"{'='*80}", Colors.BOLD)
    
    test_results = {
        "pdf_engine": {},
        "html_preview": {},
        "admin_render": False,
        "role_access": False
    }
    
    for inv_type, invoice in invoices_by_type.items():
        invoice_id = invoice["id"]
        invoice_number = invoice["invoice_number"]
        
        # Determine which token to use based on invoice owner
        if invoice.get("customer_id"):
            token = customer_token
        elif invoice.get("partner_id"):
            token = partner_token
        elif invoice.get("merchant_id"):
            token = merchant_token
        else:
            token = admin_token
        
        # Test PDF engine
        pdf_pass = test_pdf_engine(token, invoice_id, inv_type, invoice_number)
        test_results["pdf_engine"][inv_type] = pdf_pass
        
        # Test HTML preview
        html_pass = test_html_preview(token, invoice_id, inv_type, invoice_number)
        test_results["html_preview"][inv_type] = html_pass
    
    # Test admin render endpoint
    log(f"\n{'='*80}", Colors.BOLD)
    log(f"TEST 4: ADMIN RENDER ENDPOINT", Colors.BOLD)
    log(f"{'='*80}", Colors.BOLD)
    
    test_results["admin_render"] = test_admin_render_endpoint(admin_token)
    
    # Test role access
    log(f"\n{'='*80}", Colors.BOLD)
    log(f"TEST 5: ROLE ACCESS + REGRESSION", Colors.BOLD)
    log(f"{'='*80}", Colors.BOLD)
    
    test_results["role_access"] = test_role_access(customer_token, partner_token, merchant_token, admin_token)
    
    # Summary
    log(f"\n{'='*80}", Colors.BOLD)
    log(f"TEST SUMMARY", Colors.BOLD)
    log(f"{'='*80}\n", Colors.BOLD)
    
    total_tests = 0
    passed_tests = 0
    
    log(f"TEST 1: INVOICE PDF ENGINE (WeasyPrint vs ReportLab)", Colors.BOLD)
    for inv_type, result in test_results["pdf_engine"].items():
        total_tests += 1
        if result:
            passed_tests += 1
            log(f"  ✅ {inv_type.upper()}: PASS", Colors.GREEN)
        else:
            log(f"  ❌ {inv_type.upper()}: FAIL", Colors.RED)
    
    log(f"\nTEST 2: HTML PREVIEW WELL-FORMED", Colors.BOLD)
    for inv_type, result in test_results["html_preview"].items():
        total_tests += 1
        if result:
            passed_tests += 1
            log(f"  ✅ {inv_type.upper()}: PASS", Colors.GREEN)
        else:
            log(f"  ❌ {inv_type.upper()}: FAIL", Colors.RED)
    
