def test_role_access(customer_token, partner_token, merchant_token, admin_token):
    """
    TEST 5: ROLE ACCESS + REGRESSION
    - Customer can fetch their own invoice
    - Partner can fetch their own invoice
    - Merchant can fetch their own invoice
    - Cross-user access is blocked (403/404)
    """
    log(f"\n🔒 Testing role-based access control...", Colors.BLUE)
    
    # Get customer invoices
    log(f"\n  Testing customer access...", Colors.BLUE)
    customer_headers = {"Authorization": f"Bearer {customer_token}"}
    resp = requests.get(f"{BASE_URL}/invoices", headers=customer_headers)
    if resp.status_code != 200:
        log(f"    ❌ Customer cannot fetch their invoices: {resp.status_code}", Colors.RED)
        return False
    customer_invoices = resp.json().get("invoices", [])
    log(f"    ✅ Customer can fetch their invoices ({len(customer_invoices)} found)", Colors.GREEN)
    
    if customer_invoices:
        # Customer can fetch their own invoice PDF
        invoice_id = customer_invoices[0]["id"]
        resp = requests.get(f"{BASE_URL}/invoices/{invoice_id}/pdf", headers=customer_headers)
        if resp.status_code != 200:
            log(f"    ❌ Customer cannot fetch their own invoice PDF: {resp.status_code}", Colors.RED)
            return False
        log(f"    ✅ Customer can fetch their own invoice PDF", Colors.GREEN)
    
    # Get partner invoices
    log(f"\n  Testing partner access...", Colors.BLUE)
    partner_headers = {"Authorization": f"Bearer {partner_token}"}
    resp = requests.get(f"{BASE_URL}/invoices", headers=partner_headers)
    if resp.status_code != 200:
        log(f"    ❌ Partner cannot fetch their invoices: {resp.status_code}", Colors.RED)
        return False
    partner_invoices = resp.json().get("invoices", [])
    log(f"    ✅ Partner can fetch their invoices ({len(partner_invoices)} found)", Colors.GREEN)
    
    # Get merchant invoices
    log(f"\n  Testing merchant access...", Colors.BLUE)
    merchant_headers = {"Authorization": f"Bearer {merchant_token}"}
    resp = requests.get(f"{BASE_URL}/invoices", headers=merchant_headers)
    if resp.status_code != 200:
        log(f"    ❌ Merchant cannot fetch their invoices: {resp.status_code}", Colors.RED)
        return False
    merchant_invoices = resp.json().get("invoices", [])
    log(f"    ✅ Merchant can fetch their invoices ({len(merchant_invoices)} found)", Colors.GREEN)
    
    # Test cross-user access (customer trying to access partner invoice)
    if partner_invoices and customer_invoices:
        log(f"\n  Testing cross-user access blocking...", Colors.BLUE)
        partner_invoice_id = partner_invoices[0]["id"]
        resp = requests.get(f"{BASE_URL}/invoices/{partner_invoice_id}/pdf", headers=customer_headers)
        if resp.status_code == 200:
            log(f"    ❌ Customer can access partner invoice (should be blocked)", Colors.RED)
            return False
        if resp.status_code not in [403, 404]:
            log(f"    ⚠️  Unexpected status code {resp.status_code} (expected 403 or 404)", Colors.YELLOW)
        log(f"    ✅ Cross-user access blocked ({resp.status_code})", Colors.GREEN)
    
    return True

def main():
    log(f"\n{'='*80}", Colors.BOLD)
    log(f"INVOICE PREVIEW = PDF DOWNLOAD = PRINT FIX - COMPREHENSIVE TEST", Colors.BOLD)
    log(f"{'='*80}\n", Colors.BOLD)
    
