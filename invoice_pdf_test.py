class Colors:
    GREEN = '\033[92m'
    RED = '\033[91m'
    YELLOW = '\033[93m'
    BLUE = '\033[94m'
    RESET = '\033[0m'
    BOLD = '\033[1m'

def log(msg, color=Colors.RESET):
    print(f"{color}{msg}{Colors.RESET}")

def login(phone):
    """Login and return auth token"""
    log(f"\n🔐 Logging in as {phone}...", Colors.BLUE)
    
    # Request OTP
    resp = requests.post(f"{BASE_URL}/auth/send-otp", json={"phone": phone})
    if resp.status_code != 200:
        log(f"❌ OTP request failed: {resp.status_code} {resp.text}", Colors.RED)
        return None
    
    # Verify OTP
    resp = requests.post(f"{BASE_URL}/auth/verify-otp", json={"phone": phone, "otp": OTP})
    if resp.status_code != 200:
        log(f"❌ OTP verify failed: {resp.status_code} {resp.text}", Colors.RED)
        return None
    
    data = resp.json()
    token = data.get("token")
    log(f"✅ Logged in successfully", Colors.GREEN)
    return token

def get_invoices_by_type(token, invoice_type):
    """Get invoices of a specific type"""
    headers = {"Authorization": f"Bearer {token}"}
    params = {"invoice_type": invoice_type, "page_size": 50}
    resp = requests.get(f"{BASE_URL}/invoices", headers=headers, params=params)
    if resp.status_code != 200:
        return []
    data = resp.json()
    return data.get("invoices", [])

def test_pdf_engine(token, invoice_id, invoice_type, invoice_number):
    """
    TEST 1: INVOICE PDF ENGINE
    - Verify PDF is generated by WeasyPrint (NOT reportlab)
    - reportlab PDFs contain "ReportLab" string, WeasyPrint ones don't
    """
    log(f"\n📄 Testing PDF for {invoice_type} invoice {invoice_number}...", Colors.BLUE)
    
    headers = {"Authorization": f"Bearer {token}"}
    resp = requests.get(f"{BASE_URL}/invoices/{invoice_id}/pdf", headers=headers)
    
    # Check HTTP status
    if resp.status_code != 200:
        log(f"  ❌ HTTP {resp.status_code} (expected 200)", Colors.RED)
        return False
    log(f"  ✅ HTTP 200", Colors.GREEN)
    
    # Check content-type
    content_type = resp.headers.get("content-type", "")
    if "application/pdf" not in content_type and "application/octet-stream" not in content_type:
        log(f"  ❌ Content-Type: {content_type} (expected application/pdf)", Colors.RED)
        return False
    log(f"  ✅ Content-Type: {content_type}", Colors.GREEN)
    
    # Check PDF magic bytes
    pdf_bytes = resp.content
    if len(pdf_bytes) == 0:
        log(f"  ❌ Empty PDF body", Colors.RED)
        return False
    log(f"  ✅ PDF body size: {len(pdf_bytes)} bytes", Colors.GREEN)
    
    if not pdf_bytes.startswith(b"%PDF"):
        log(f"  ❌ PDF does not start with %PDF magic bytes", Colors.RED)
        return False
    log(f"  ✅ PDF starts with %PDF magic bytes", Colors.GREEN)
    
    # CRITICAL: Check if PDF was generated by WeasyPrint (NOT reportlab)
    # reportlab PDFs contain the literal "ReportLab" producer string
    # WeasyPrint PDFs do NOT contain "ReportLab"
    first_3000_bytes = pdf_bytes[:3000]
    if b"ReportLab" in first_3000_bytes:
        log(f"  ❌ CRITICAL: PDF contains 'ReportLab' in first 3000 bytes - PDF was generated by reportlab fallback, NOT WeasyPrint!", Colors.RED)
        return False
    log(f"  ✅ CRITICAL: PDF does NOT contain 'ReportLab' - PDF was generated by WeasyPrint", Colors.GREEN)
    
    # Check entire PDF for ReportLab (ideally should not appear anywhere)
    if b"ReportLab" in pdf_bytes:
        log(f"  ⚠️  WARNING: PDF contains 'ReportLab' somewhere (not in first 3000 bytes)", Colors.YELLOW)
    else:
        log(f"  ✅ PDF does NOT contain 'ReportLab' anywhere - confirmed WeasyPrint", Colors.GREEN)
    
    return True

def test_html_preview(token, invoice_id, invoice_type, invoice_number):
    """
    TEST 2: HTML PREVIEW WELL-FORMED
    - Verify HTML contains proper content and key financial labels
    """
    log(f"\n🌐 Testing HTML preview for {invoice_type} invoice {invoice_number}...", Colors.BLUE)
    
    headers = {"Authorization": f"Bearer {token}"}
    resp = requests.get(f"{BASE_URL}/invoices/{invoice_id}/view", headers=headers)
    
    # Check HTTP status
    if resp.status_code != 200:
        log(f"  ❌ HTTP {resp.status_code} (expected 200)", Colors.RED)
        return False
    log(f"  ✅ HTTP 200", Colors.GREEN)
    
    # Check content-type
    content_type = resp.headers.get("content-type", "")
    if "text/html" not in content_type:
        log(f"  ❌ Content-Type: {content_type} (expected text/html)", Colors.RED)
        return False
    log(f"  ✅ Content-Type: {content_type}", Colors.GREEN)
    
    html = resp.text
    
    # Check HTML structure
    if "<html" not in html.lower():
        log(f"  ❌ HTML does not contain <html tag", Colors.RED)
        return False
    log(f"  ✅ HTML contains <html tag", Colors.GREEN)
    
    # Check invoice number
    if invoice_number not in html:
        log(f"  ❌ HTML does not contain invoice number {invoice_number}", Colors.RED)
        return False
    log(f"  ✅ HTML contains invoice number {invoice_number}", Colors.GREEN)
    
    # Check key financial labels based on invoice type
    if invoice_type == "cancellation":
        # For cancellation: should have "Total Customer Refund" and NOT "Cancellation Charge"
        if "Total Customer Refund" not in html:
            log(f"  ❌ Cancellation invoice does NOT contain 'Total Customer Refund'", Colors.RED)
            return False
        log(f"  ✅ Cancellation invoice contains 'Total Customer Refund'", Colors.GREEN)
        
        if "Cancellation Charge" in html:
            log(f"  ❌ Cancellation invoice contains 'Cancellation Charge' (should not)", Colors.RED)
            return False
        log(f"  ✅ Cancellation invoice does NOT contain 'Cancellation Charge'", Colors.GREEN)
    
    elif invoice_type == "booking":
        # For tax invoice: should have "TOTAL" or "Total"
        if "TOTAL" not in html.upper():
            log(f"  ❌ Tax invoice does NOT contain 'TOTAL'", Colors.RED)
            return False
        log(f"  ✅ Tax invoice contains 'TOTAL'", Colors.GREEN)
    
    return True

